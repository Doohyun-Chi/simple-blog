-- Post table, see DBSCHEMA.md. The schema is not managed by Hibernate (ddl-auto=none): run this once.
-- TB_POST_MIGRATION.sql copies the WordPress wp_posts into it.

CREATE TABLE IF NOT EXISTS TB_POST (
  ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  SLUG VARCHAR(200) NOT NULL,
  TITLE VARCHAR(200) NOT NULL,
  STATUS VARCHAR(20) NOT NULL,
  TYPE VARCHAR(20) NOT NULL,
  CONTENT LONGTEXT NOT NULL,
  AUTHOR_ID BIGINT UNSIGNED NOT NULL,
  HASH_TAGS VARCHAR(200) NULL,
  SNS_LINK VARCHAR(2048) NULL,
  CREATED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC',
  MODIFIED_DATETIME DATETIME(6) NOT NULL COMMENT 'UTC',
  PRIMARY KEY (ID),
  UNIQUE INDEX IDX_TB_POST_SLUG (SLUG),
  INDEX IDX_TB_POST_CREATED_DATETIME (CREATED_DATETIME DESC),
  INDEX IDX_TB_POST_TYPE (TYPE),
  INDEX IDX_TB_POST_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
