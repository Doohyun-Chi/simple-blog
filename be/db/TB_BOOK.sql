-- Bookshelf table, see DBSCHEMA.md. The schema is not managed by Hibernate (ddl-auto=none): run this once.
CREATE TABLE IF NOT EXISTS TB_BOOK (
  ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  TITLE VARCHAR(300) NOT NULL,
  AUTHOR VARCHAR(200) NULL,
  BOOKSTORE_URL VARCHAR(2000) NOT NULL,
  THUMBNAIL_URL VARCHAR(2000) NULL,
  DESCRIPTION TEXT NULL,
  INSIGHT TEXT NULL,
  TRACKBACK_SLUG VARCHAR(200) NULL,
  REGISTERED_DATE DATE NOT NULL,
  READING_START_DATE DATE NULL,
  READING_COMPLETE_DATE DATE NULL,
  READER_ID BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (ID),
  INDEX IDX_TB_BOOK_REGISTERED_DATE (REGISTERED_DATE DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
